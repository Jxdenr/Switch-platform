"""Vendor quality from real receipts, with warnings for receipts that look generated.

Fake-DLR tells (as described by testing services such as TelQ and by CM.com):
  * almost every message DELIVRD, with no failures at all, on a real volume,
  * receipts arriving within a second or two of sending, every time,
  * receipt delays that are nearly identical across messages,
  * lots of messages with no receipt at all (the route is losing them, or the DLR path is broken).
These flags are a prompt to live-test the route with real handsets. They are not proof.
"""
from datetime import timedelta
from statistics import median

from django.db.models import Count, Q
from django.utils import timezone

from .models import OutboundMessage as M, Vendor


def pct(n, d):
    return round(100.0 * n / d, 1) if d else None


def vendor_quality(days=7, vendor_ids=None):
    since = timezone.now() - timedelta(days=days)
    base = M.objects.filter(created_at__gte=since, test=False, vendor__isnull=False)
    if vendor_ids:
        base = base.filter(vendor_id__in=vendor_ids)
    counts = {r["vendor_id"]: r for r in base.values("vendor_id").annotate(
        sent=Count("pk"),
        delivered=Count("pk", filter=Q(status=M.DELIVERED)),
        failed=Count("pk", filter=Q(status__in=[M.UNDELIVERED, M.EXPIRED, M.REJECTED])),
        waiting=Count("pk", filter=Q(status=M.SUBMITTED)),
        no_receipt=Count("pk", filter=Q(no_receipt=True)),
        unknown=Count("pk", filter=Q(status=M.UNKNOWN)))}
    rows = []
    for v in Vendor.objects.select_related("account").filter(account_id__in=counts.keys()) if counts else []:
        c = counts[v.account_id]
        delays = [
            (d - s).total_seconds() for s, d in
            base.filter(vendor_id=v.account_id, status__in=M.FINAL, submitted_at__isnull=False,
                        dlr_received_at__isnull=False).order_by("-created_at")
            .values_list("submitted_at", "dlr_received_at")[:5000]]
        final = c["sent"] - c["waiting"]
        row = {"vendor": v, **c, "final": final,
               "delivered_pct": pct(c["delivered"], final), "no_receipt_pct": pct(c["no_receipt"], final),
               "median_delay": round(median(delays), 1) if delays else None, "flags": []}
        if delays:
            s = sorted(delays)
            row["p10"], row["p90"] = round(s[len(s) // 10], 1), round(s[(len(s) * 9) // 10], 1)
        row["flags"] = flags(row, delays)
        rows.append(row)
    rows.sort(key=lambda r: -r["sent"])
    return rows


def flags(row, delays):
    out = []
    final = row["final"]
    if final >= 200 and row["failed"] == 0 and (row["delivered_pct"] or 0) >= 99.5:
        out.append("Almost every message is DELIVRD with no failures. Real routes nearly always have some. "
                   "Live-test this route.")
    if len(delays) >= 50:
        s = sorted(delays)
        p10, p90 = s[len(s) // 10], s[(len(s) * 9) // 10]
        if median(s) < 1.5:
            out.append(f"Receipts arrive in {median(s):.1f}s on average. Real network receipts usually take "
                       "several seconds. Receipts this fast are often generated by the vendor.")
        if p90 - p10 < 1.0:
            out.append("Receipt delays are almost identical for every message, which suggests they are generated.")
    if final >= 50 and (row["no_receipt_pct"] or 0) >= 20:
        out.append(f"{row['no_receipt_pct']}% of messages never got a receipt. Either the route loses messages or "
                   "its receipts don't reach us (check the bind and ID format).")
    return out
